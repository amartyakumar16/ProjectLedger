const { chromium } = require(require('path').join(require('os').tmpdir(), 'projectledger-document-tools/node_modules/playwright-core'));
const path = require('path');
const fs = require('fs');
const assert = require('assert/strict');

(async () => {
  const out = path.join(__dirname, 'images');
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1.5, timezoneId: 'America/New_York', acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const shot = async (name, locator) => { await locator.screenshot({ path: path.join(out, name + '.png'), animations: 'disabled' }); console.log('Captured ' + name); };
  try {
    await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
    await shot('01-sign-in', page.locator('.login-card'));
    await page.getByRole('button', { name: /Aakash Kumar/ }).click();
    await page.getByRole('heading', { name: /Good / }).waitFor();
    await page.screenshot({ path: path.join(out, '02-dashboard.png'), clip: { x: 0, y: 0, width: 1600, height: 430 } });
    await page.goto('http://localhost:5173/pdf-to-excel');
    await page.getByLabel('Upload PDF or image').setInputFiles(path.join(__dirname, 'sample-purchase-order.pdf'));
    await page.getByLabel('Text recognition').selectOption('never');
    await page.getByRole('button', { name: 'Read document & create tables' }).click();
    await page.getByLabel('Row 1, Item no.', { exact: true }).waitFor({ timeout: 60000 });
    assert.equal(await page.getByLabel('Row 1, Quantity', { exact: true }).inputValue(), '40.000');
    const grid = page.locator('.pdf-table');
    const headings = await grid.locator('thead input').evaluateAll((nodes) => nodes.map((n) => n.value));
    assert(!headings.includes('Source pages') && !headings.includes('Review notes'));
    const item = page.getByLabel('Row 1, Item no.', { exact: true });
    await item.focus();
    await item.evaluate((el) => el.setSelectionRange(2, 2));
    await page.keyboard.press('ArrowRight');
    await page.getByLabel('Row 1, Material no.', { exact: true }).evaluate((el) => { if (el !== document.activeElement) throw new Error('Right arrow did not move to next cell'); });
    await page.keyboard.press('ArrowLeft');
    await item.evaluate((el) => { if (el !== document.activeElement) throw new Error('Left arrow did not move to previous cell'); });
    await shot('03-table-start', grid.locator('..'));
    const last = page.getByLabel('Row 1, Unloading point', { exact: true });
    await last.focus();
    await page.keyboard.press('ArrowRight');
    await page.getByLabel('Delete row 1', { exact: true }).evaluate((el) => { if (el !== document.activeElement) throw new Error('Delete button not in arrow navigation'); });
    await page.keyboard.press('ArrowRight');
    await page.getByLabel('Select row 1 for data check', { exact: true }).evaluate((el) => { if (el !== document.activeElement) throw new Error('Checkbox not in arrow navigation'); });
    await page.getByLabel('Select row 1 for data check', { exact: true }).check();
    await shot('04-select-row', grid.locator('..'));
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download Excel (.xlsx)' }).click()]);
    await download.saveAs(path.join(__dirname, 'sample-converted-tables.xlsx'));
    await page.getByRole('button', { name: 'Request data check', exact: true }).click();
    await page.getByLabel('Project manager', { exact: true }).selectOption('u3');
    await page.getByLabel('What should they check?', { exact: true }).fill('Please verify Quantity 40.000 and Gross price 255.000 in row 1 against the purchase order.');
    await shot('05-send-request', page.getByRole('dialog'));
    await page.getByRole('button', { name: 'Send request', exact: true }).click();
    const active = page.getByRole('region', { name: 'Active Requests', exact: true });
    await active.getByRole('heading', { name: /sample-purchase-order/ }).waitFor();
    await shot('06-active-request', active);
    const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('projectledger.v1')));
    const requestId = snapshot.pdfDataChecks[0].id;
    await page.getByRole('button', { name: 'Switch user', exact: true }).click();
    await page.getByRole('button', { name: /Rohan Mehta/ }).click();
    await page.goto('http://localhost:5173/notifications');
    const notification = page.locator('.notif').filter({ hasText: 'Data check requested' });
    await shot('07-manager-notification', notification);
    await notification.getByRole('button', { name: 'Open', exact: true }).click();
    await page.getByRole('region', { name: 'Active Requests', exact: true }).getByLabel('Check result / corrections').fill('Quantity and gross price match the sample purchase order.');
    await shot('08-manager-review', page.getByRole('region', { name: 'Active Requests', exact: true }));
    await page.getByRole('region', { name: 'Active Requests', exact: true }).getByRole('button', { name: 'Mark as checked', exact: true }).first().click();
    const closed = page.getByRole('region', { name: 'Closed Requests', exact: true });
    await closed.getByText('Checked', { exact: true }).first().waitFor();
    assert.equal(await page.getByRole('region', { name: 'Active Requests', exact: true }).getByRole('button', { name: 'View request', exact: true }).count(), 0);
    assert.equal(await closed.getByRole('button', { name: 'View request', exact: true }).count(), 1);
    await page.screenshot({ path: path.join(out, '09-closed-requests.png'), clip: { x: 254, y: 76, width: 1322, height: 840 } });
    await page.reload();
    await page.getByRole('region', { name: 'Closed Requests', exact: true }).getByRole('button', { name: 'View request', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Switch user', exact: true }).click();
    await page.getByRole('button', { name: /Aakash Kumar/ }).click();
    await page.goto('http://localhost:5173/notifications');
    await shot('10-requester-result', page.locator('.notif').filter({ hasText: 'Data check: Checked' }));
    await page.goto(`http://localhost:5173/pdf-to-excel?check=${requestId}`);
    await shot('11-closed-details', page.getByRole('region', { name: 'Closed Requests', exact: true }));
    await page.getByRole('button', { name: 'Close details', exact: true }).click();
    const activeBox = await page.getByRole('region', { name: 'Active Requests', exact: true }).boundingBox();
    const closedBox = await page.getByRole('region', { name: 'Closed Requests', exact: true }).boundingBox();
    await page.screenshot({ path: path.join(out, '12-active-and-closed.png'), clip: { x: activeBox.x, y: activeBox.y, width: activeBox.width, height: closedBox.y + closedBox.height - activeBox.y } });
    const ExcelJS = require(path.resolve(__dirname, '../../node_modules/exceljs'));
    const book = new ExcelJS.Workbook();
    await book.xlsx.readFile(path.join(__dirname, 'sample-converted-tables.xlsx'));
    const cols = book.getWorksheet('Purchase order items').getRow(1).values;
    assert(!cols.includes('Source pages') && !cols.includes('Review notes'));
    const evidence = { capturedAt: new Date().toISOString(), sampleData: true, requestId, browserErrors: errors, checks: ['Branding visible', 'PDF upload and extraction', 'Removed columns absent from table and XLSX', 'Right and left navigation from mid-text', 'Delete and checkbox navigation', 'Request snapshot and manager notification', 'Manager review and requester result notification', 'Automatic transfer to Closed Requests', 'Closed request retained after reload'] };
    fs.writeFileSync(path.join(__dirname, 'capture-verification.json'), JSON.stringify(evidence, null, 2));
    assert.equal(errors.length, 0, 'Browser errors found');
    console.log('All screenshot walkthrough checks passed.');
  } finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exitCode = 1; });
